export function getValidityIntegrityScore(data: {
  fullyCompliantResults: number;
  totalResultsPublished: number;
}): number {
  if (data.totalResultsPublished <= 0) return 0;
  return (data.fullyCompliantResults / data.totalResultsPublished) * 100;
}
